/**
 * Proving what a check declared it needs, before it is asked to grade anything.
 *
 * A check that could not run has said nothing about the code. The evaluation
 * already knows how to report that — `prerequisite-missing`, normalized to
 * `unverified`, which denies authoritatively — and it already filters each
 * check's declared prerequisites through a resolver. This module is the
 * resolver both production runners bind, in place of the stub that asserted
 * every declaration proved without establishing anything (`TB-044`).
 *
 * Two rules shape everything here.
 *
 * Nothing is inferred. No exit code, error string, or line of tool output is
 * read to decide that a failure "looks like" an environment fault. A
 * prerequisite is declared by whoever owns the check, and it is either proved
 * against facts this evaluation already established or it is not proved at all.
 * A heuristic would be worse than the defect it replaces, because it would
 * sometimes hide a real failure of the code.
 *
 * Nothing here is a tool. This module learns no tool name, no flag, and no
 * stack: it is given a kind and a name, and it answers from the environment the
 * Gate itself created and the runtime it itself resolved (`SG-OWNER-001`).
 *
 * Every unknown answers `false`. An unreadable declaration, a kind with no
 * proof, a fact this environment cannot state: each is a requirement that was
 * not proved, which is what `unverified` means (`NFR-REL-003`).
 */

import { environmentFor } from './bounded-execution.mjs';
import { locateOnPath } from './command-descriptor.mjs';

/**
 * The facts this Gate can state about the environment it built.
 *
 * They are properties of the evaluation, not of anybody's toolchain: a check
 * declares that it needs one, and the Gate either established it or did not.
 * A name that is not one of these is read as an environment variable the check
 * needs delivered to it, which is the other thing an evaluation environment
 * can be asked for and the only other thing it can answer.
 */
const ENVIRONMENT_FACTS = Object.freeze({
  /**
   * Whether the tree the checks run against carries source-control history.
   *
   * It is derived, never asserted: the fact holds only where the executed tree
   * IS the repository. An evaluation materializes an exact snapshot somewhere
   * else precisely so the graded tree cannot move (`SG-EVAL-001`), and a
   * materialized tree is a tree of files with no repository — so a command
   * whose arguments depend on one cannot run in it, and says so instead of
   * reporting whatever its refusal to start looked like.
   */
  'source-control-history': ({ snapshot, repositoryRoot }) => typeof repositoryRoot === 'string'
    && repositoryRoot.length > 0
    && snapshot?.executionRoot === repositoryRoot,
});

const posix = (value) => String(value).replace(/\\/g, '/').replace(/\/+$/, '');

/**
 * Whether the evaluated tree holds one declared repository-relative path.
 *
 * The answer is read from what materialization already established — the
 * snapshot's own path list and the dependency roots that were provided beside
 * it — rather than by walking the execution root a second time. A path that is
 * generated by a build step is tracked by nothing, so it is in neither list and
 * is not proved: the check that reads it is `unverified` naming the path,
 * instead of reporting a verdict about imports that were never there.
 */
const holdsPath = (paths, declared) => {
  const wanted = posix(declared);

  if (wanted === '') {
    return false;
  }

  return paths.some((entry) => {
    const held = posix(entry);

    return held === wanted || held.startsWith(`${wanted}/`);
  });
};

/**
 * Whether the check will actually be given a named environment variable.
 *
 * Asked of the one function that builds a check's environment, so the answer
 * cannot drift from what execution delivers. A check runs with the names its
 * descriptor declared and nothing of the invoking shell, which is what makes an
 * evaluation reproducible — and also what makes a setting a maintainer's own
 * shell supplies absent here unless the project declared it. Declared and
 * absent is reported by name; it is never discovered from what the tool
 * printed when it ran without it.
 */
const delivered = (name, { check, environment, searchPath }) => {
  const value = environmentFor(
    check?.evaluate?.allowed_environment ?? [],
    environment ?? {},
    searchPath ?? '',
  )[name];

  return typeof value === 'string' && value.length > 0;
};

/**
 * What proves one requirement of each declared kind.
 *
 * `service` has no entry with an honest proof: nothing in this Gate probes a
 * service, and a probe is not something this slice adds. A declared service is
 * therefore never proved, which is the fail-closed answer — absence of evidence
 * has never been evidence of presence (`NFR-REL-003`).
 */
const PROOFS = Object.freeze({
  executable: ({ name }, { searchPath }) => locateOnPath(name, { PATH: searchPath ?? '' }) !== null,
  configuration: ({ name }, { evaluatedPaths }) => holdsPath(evaluatedPaths ?? [], name),
  service: () => false,
  environment: ({ name }, context) => {
    const fact = Object.prototype.hasOwnProperty.call(ENVIRONMENT_FACTS, name)
      ? ENVIRONMENT_FACTS[name]
      : null;

    return fact === null ? delivered(name, context) : fact(context) === true;
  },
});

/**
 * Name one unproved requirement the way a maintainer reads it.
 *
 * `NFR-OPER-001`: a denial is diagnosable without opening a tool's own logs, so
 * what was not proved is stated in the decision rather than left to be inferred
 * from the error text of a program that never started.
 *
 * @param {object} prerequisite one declared prerequisite
 * @returns {string} the kind and name, as declared
 */
export const describePrerequisite = (prerequisite) => `${prerequisite?.kind ?? 'unknown'} ${JSON.stringify(prerequisite?.name ?? null)}`;

/**
 * The one sentence an unverified check carries when a requirement was not
 * proved.
 *
 * @param {object[]} missing the prerequisites that were not proved
 * @returns {string} a readable statement naming each of them
 */
export const describeMissingPrerequisites = (missing = []) => `this check did not run because ${missing.length === 1 ? 'a requirement it declared was' : 'requirements it declared were'} not proved for this evaluation: ${missing.map(describePrerequisite).join(', ')}. Nothing here is a finding about the code.`;

/**
 * Bind a resolver to the environment one runner is about to evaluate in.
 *
 * The runner supplies what only it knows — the search path its pinned programs
 * run with and the environment this invocation carries — and the evaluation
 * supplies what only it knows, per check: the snapshot it materialized, the
 * dependency roots it provided, and the descriptor being resolved. Neither
 * re-establishes the other's facts, so there is one answer to each question
 * and no second copy to drift.
 *
 * @param {object} runtime the search path and environment checks will run with
 * @returns {(prerequisite: object, context: object) => boolean} the resolver
 */
export const createPrerequisiteResolver = ({ searchPath = '', environment = {} } = {}) => (
  prerequisite,
  context = {},
) => {
  const prove = PROOFS[prerequisite?.kind] ?? null;

  if (prove === null) {
    return false;
  }

  return prove(prerequisite, { ...context, searchPath, environment }) === true;
};
